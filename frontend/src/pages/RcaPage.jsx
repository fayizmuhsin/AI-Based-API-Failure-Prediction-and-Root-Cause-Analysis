import PageHeading from '../components/PageHeading.jsx'
import StatePanel from '../components/StatePanel.jsx'
import StatusBadge from '../components/StatusBadge.jsx'
import { SERVICES } from '../services/api.js'
import { formatDate } from '../services/format.js'

export default function RcaPage({ snapshot, selectedId, detail, candidates, loading, error, onSelect, onClose }) {
  const investigations = snapshot.investigations?.items || []
  const selected = detail?.investigation_id === selectedId ? detail : null
  return (
    <>
      <PageHeading eyebrow="Investigation / Phase 6" title="Root cause analysis"
        description="Evidence-backed candidate ranking across correlated anomalies, telemetry, traces, and caller-to-dependency relationships." />
      <section className="rca-summary-grid">
        <SummaryStat label="Total investigations" value={snapshot.investigationSummary?.total_investigations ?? '—'} />
        <SummaryStat label="Completed" value={snapshot.investigationSummary?.completed ?? '—'} />
        <SummaryStat label="Inconclusive" value={snapshot.investigationSummary?.inconclusive ?? '—'} />
        <SummaryStat label="Pending analysis" value={snapshot.investigationSummary?.pending_anomalies ?? '—'} />
      </section>
      <section className="panel section-block">
        <div className="panel-heading"><div><h2>Investigation history</h2><p>Latest reports generated by observed anomaly episodes.</p></div></div>
        {snapshot.errors.investigations && !snapshot.investigations ? <StatePanel kind="error" title="Investigations unavailable" message={snapshot.errors.investigations} />
          : !snapshot.investigations ? <StatePanel kind="loading" title="Loading investigations" message="Connecting to the RCA API." />
            : investigations.length === 0 ? <StatePanel title="No investigations yet" message="An investigation is generated after the background worker processes a detected anomaly." />
              : <div className="table-scroll"><table className="data-table">
                <thead><tr><th>Investigation</th><th>Episode</th><th>Status</th><th>Triggers</th><th>Candidates</th><th>Created</th></tr></thead>
                <tbody>{investigations.map((item) => <tr key={item.investigation_id} className={selectedId === item.investigation_id ? 'row-selected' : ''}>
                  <td><button className="table-link" onClick={() => onSelect(item.investigation_id)}>{item.investigation_id.slice(0, 8)}…</button></td>
                  <td>{formatDate(item.episode_start)}</td><td><StatusBadge status={item.status} compact /></td>
                  <td>{item.trigger_count}</td><td>{item.candidate_count}</td><td>{formatDate(item.created_at)}</td>
                </tr>)}</tbody>
              </table></div>}
      </section>
      {selectedId && <section className="panel detail-panel section-block">
        <div className="panel-heading"><div><p className="eyebrow">Investigation details</p><h2>{selectedId}</h2></div>
          <button className="icon-button" onClick={onClose} aria-label="Close investigation details">×</button></div>
        {loading ? <StatePanel kind="loading" title="Loading investigation" message="Fetching candidates and supporting evidence." />
          : error ? <StatePanel kind="error" title="Could not load investigation" message={error} />
            : selected ? <InvestigationEvidence report={selected} candidates={candidates || selected.candidates || []} />
              : <StatePanel title="Investigation not available" message="Select a report from the history." />}
      </section>}
    </>
  )
}

function SummaryStat({ label, value }) {
  return <div className="summary-stat"><span>{label}</span><strong>{value}</strong></div>
}

function InvestigationEvidence({ report, candidates }) {
  return <>
    <div className={`investigation-conclusion conclusion-${report.status}`}>
      <StatusBadge status={report.status} />
      <div><strong>{report.conclusion}</strong><p>Candidate rankings are evidence-based points, not failure probabilities or confirmation.</p></div>
    </div>
    <div className="evidence-summary">
      <div><small>Episode</small><strong>{formatDate(report.episode_start)} – {formatDate(report.episode_end)}</strong></div>
      <div><small>Trigger anomalies</small><strong>{(report.triggering_anomaly_ids || []).map((id) => `#${id}`).join(', ') || '—'}</strong></div>
      <div><small>Telemetry examined</small><strong>{report.evidence_summary?.telemetry_records_examined ?? '—'} records</strong></div>
      <div><small>Trace groups</small><strong>{report.evidence_summary?.correlated_trace_groups ?? '—'}</strong></div>
    </div>
    <h3 className="subsection-title">Ranked probable causes and candidates</h3>
    {candidates.length ? <div className="candidate-list">{candidates.map((candidate) => <article key={`${candidate.rank}-${candidate.service_id}`}
      className={`candidate-card ${candidate.rank === 1 ? 'candidate-top' : ''}`}>
      <div className="candidate-rank">#{candidate.rank}</div>
      <div className="candidate-content">
        <div className="candidate-head"><div><strong>{candidate.service_name}</strong><span>{candidate.category.replaceAll('_', ' ')}</span></div>
          <div className="candidate-score"><strong>{candidate.rank_score.toFixed(1)}</strong><small>ranking pts</small></div></div>
        <p>{candidate.explanation}</p>
        <div className="candidate-tags"><StatusBadge status={candidate.evidence_strength} compact />
          {candidate.selected_as_probable_root_cause && <span className="probable-tag">Probable candidate</span>}
          <span>{candidate.supporting_signal_count} signal types</span></div>
        {candidate.affected_services?.length > 0 && <div className="affected-line"><small>Potentially affected:</small> {candidate.affected_services.map((id) => SERVICES.find((service) => service.id === id)?.name || id).join(', ')}</div>}
        <details className="candidate-evidence"><summary>Supporting evidence ({candidate.evidence?.length || 0})</summary>
          <div className="evidence-list">{candidate.evidence?.map((evidence, index) => <div className="evidence-item" key={`${evidence.reference_id}-${index}`}>
            <span>{evidence.source.replaceAll('_', ' ')}</span><strong>{evidence.summary}</strong>
            <small>{formatDate(evidence.timestamp)} · ref {evidence.reference_id}</small>
          </div>)}</div>
        </details>
      </div>
    </article>)}</div> : <StatePanel title="No ranked candidates" message="No service had sufficient observed evidence to evaluate." />}
    <p className="score-notice">{report.methodology?.dependency_direction}. Scores are heuristic ranking points; an investigation does not confirm a cause.</p>
  </>
}
